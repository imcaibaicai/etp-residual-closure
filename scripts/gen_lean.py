# -*- coding: utf-8 -*-
"""Generate ETP ``Generated``-family Lean files from ``witnesses_264.json``.

按表分组：一张见证表一个文件、一条定理。定理的 ``Facts G [sat] [ref]`` 只列该表
真正答过的律——``sat`` 是它为各对提供假设侧的律，``ref`` 是它反驳的目标律，两者都
已由三条求值路径逐对验证过。

语法照抄 ``equational_theories/Generated/All4x4Tables/Refutation899.lean``：
``def «name» : Magma (Fin n) where op := finOpTable "..."`` 加
``@[equational_result] theorem «facts name» : ∃ (G : Type) (_ : Magma G)
(_ : Finite G), Facts G [...] [...] := ⟨Fin n, «name», Finite.of_fintype _,
by decideFin!⟩``。
"""

from __future__ import annotations

import json
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))   # <repo>/scripts
WS = os.path.dirname(HERE)                          # <repo>
DATA = os.path.join(WS, "data")
OUT = os.path.join(WS, "lean")

HEADER = """import Mathlib.Data.Finite.Prod
import equational_theories.Equations.All
import equational_theories.FactsSyntax
import equational_theories.MemoFinOp
import equational_theories.DecideBang

/-!
{purpose}

Generated by `scripts/gen_lean.py` from `data/witnesses_264.json`. The pairs
below are the ones from `data/etp/finite_uncovered.txt` that this one table
separates in the hypothesis-and-refute sense: it satisfies every law in the
first list and refutes every law in the second. Both sides were checked by three
independent evaluators (stack machine, naive recursion, `etp_magma_lib`).

Compiled individually with `lake env lean` against Lean 4.29.1 — 31 of 31 files
passed. This is not a full `lake build` and not a CI run; see `lean/INDEX.md`.
-/

set_option linter.unusedVariables false
"""


INDEX_HEADER = """# Lean witness files, one per table

All 31 files compile. Each was run through `lake env lean` against Lean 4.29.1, the
version pinned by the project's `lean-toolchain`: 31 passed, 0 failed, 423.4 s total.
Per-file exit codes and wall times are in
[`../data/lean_compile_check.json`](../data/lean_compile_check.json), produced by
[`check_lean_compile.py`](../scripts/check_lean_compile.py).

That is 31 individual compilations after a targeted build of the modules they import
— **not** a full `lake build`, **not** CI, and **not** a maintainer review. Read
[`../docs/06-boundaries.md`](../docs/06-boundaries.md) before describing it otherwise.

Reproducing needs the project's own modules built first: a fresh checkout carries the
dependency oleans but no `equational_theories` oleans, so the imports fail with
`unknown module prefix` until these run.

```
lake build equational_theories.Equations.All
lake build equational_theories.FactsSyntax equational_theories.MemoFinOp \\
           equational_theories.DecideBang
python3 scripts/check_lean_compile.py \\
    --project "$ETP_HOME/equational_theories" --lean-dir lean
```

Names follow the corpus' module names with `.` written as `__`: `Refutation899` comes
from `equational_theories/Generated/All4x4Tables/Refutation899.lean`. A `T` suffix in
the file name means the transpose of that table.

| file | carrier | pairs separated | satisfied laws listed | refuted laws listed |
|---|---|---|---|---|
"""


def readable_source(module_name: str) -> str:
    """Turn the corpus' module-name form back into a path a reader can follow.

    ``equational_theories__Generated__All4x4Tables__Refutation899.lean`` becomes
    ``equational_theories/Generated/All4x4Tables/Refutation899.lean``. The corpus
    records every table by Lean module name, with ``.`` written as ``__``.
    """
    name = module_name[:-2] if module_name.endswith("#T") else module_name
    return "/".join(name.split("__"))


def main():
    with open(os.path.join(DATA, "witnesses_264.json"), encoding="utf-8") as fh:
        doc = json.load(fh)
    with open(os.path.join(DATA, "tables_referenced.json"), encoding="utf-8") as fh:
        tabs = json.load(fh)["tables"]

    by_table = defaultdict(list)
    for rec in doc["records"]:
        by_table[rec["witness"]["sha256"]].append(rec)

    os.makedirs(OUT, exist_ok=True)
    written = []
    for sha, recs in sorted(by_table.items(), key=lambda kv: (tabs[kv[0]]["carrier"], kv[0])):
        meta = tabs[sha]
        table = meta["table"]
        n = meta["carrier"]
        # 见证表名可能带 "#T" 后缀表示转置；先剥后缀再剥扩展名，否则会得到 "...lean#TT"
        raw = meta["source"]
        base = raw[:-2] if raw.endswith("#T") else raw
        base = base.split("__")[-1]
        if base.endswith(".lean"):
            base = base[:-5]
        name = base + ("T" if meta["is_transpose"] else "")
        name = name.replace("-", "_")

        sats = sorted({r["from"] for r in recs})
        refs = sorted({r["to"] for r in recs})
        pairs = ", ".join(f"E{r['from']} ⊭ E{r['to']}" for r in recs)

        purpose = (
            f"One table separates {len(recs)} pair(s) from `data/etp/finite_uncovered.txt`.\n\n"
            f"{pairs}\n\n"
            f"Source: `{readable_source(meta['source'])}`"
            + (" (transposed)." if meta["is_transpose"] else ".")
        )

        body = HEADER.format(purpose=purpose)
        body += f"""
/-! The magma definition -/
@[implicit_reducible]
def «{name}» : Magma (Fin {n}) where
  op := finOpTable {json.dumps(json.dumps(table, separators=(",", ":")))}

/-! The facts -/
@[equational_result]
theorem «facts {name}» :
  ∃ (G : Type) (_ : Magma G) (_: Finite G), Facts G {sats} {refs} :=
    ⟨Fin {n}, «{name}», Finite.of_fintype _, by decideFin!⟩
"""
        path = os.path.join(OUT, f"Witness_{name}.lean")
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
        written.append((os.path.basename(path), n, len(recs), len(sats), len(refs)))

    index = os.path.join(OUT, "INDEX.md")
    with open(index, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(INDEX_HEADER)
        fh.write("| file | carrier | pairs separated | satisfied laws listed | refuted laws listed |\n")
        fh.write("|---|---|---|---|---|\n")
        for nm, n, np_, ns, nr in written:
            fh.write(f"| `{nm}` | {n} | {np_} | {ns} | {nr} |\n")
        fh.write(f"\nTotal: {len(written)} files, "
                 f"{sum(w[2] for w in written)} pairs.\n")
    print(f"wrote {len(written)} lean files to {OUT}")
    print(f"pairs covered: {sum(w[2] for w in written)}")
    for nm, n, np_, ns, nr in written[:6]:
        print(f"  {nm:34s} carrier {n:3d} pairs {np_:3d} sat {ns:3d} ref {nr:3d}")


if __name__ == "__main__":
    main()
